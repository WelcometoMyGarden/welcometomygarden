// Requires a Stripe Sandbox to be connected, see chargeAutomatically.test.js.
// Remove the .skip() on the root describe if you want to run these tests.
//
// Checks that a first payment with iDEAL or Bancontact produces a reusable SEPA Debit mandate
// that renewals are charged with, even when sepa_debit itself is not offered on the first payment.
const assert = require('node:assert');
const dotenv = require('dotenv');
const { resolve } = require('node:path');
dotenv.config({ path: resolve(__dirname, '../.env.local'), quiet: true });
if (!process.env.STAGING) {
  dotenv.config({ path: resolve(__dirname, '../.env.test.local'), quiet: true });
}

const sinon = require('sinon');
const { DateTime } = require('luxon');
const { clearAuth, clearFirestore } = require('./util/util');
const stripe = require('../src/subscriptions/stripe');
const {
  createAndLinkTestClockCustomer,
  pollForTestClockReady,
  authorizeTestRedirect,
  pollUntil
} = require('./util/stripe');
const {
  createOrRetrieveUnpaidSubscription
} = require('../src/subscriptions/createOrRetrieveUnpaidSubscription');
const { getInvoicePaymentIntent } = require('../src/subscriptions/basilCompat');

describe.skip('generated SEPA Debit mandates', () => {
  beforeEach(async () => {
    await clearAuth();
    await clearFirestore();

    // Offer every payment method except sepa_debit on the first payment
    const createSubscription = stripe.subscriptions.create.bind(stripe.subscriptions);
    sinon.stub(stripe.subscriptions, 'create').callsFake((params) =>
      createSubscription({
        ...params,
        payment_settings: {
          ...params.payment_settings,
          payment_method_types: params.payment_settings.payment_method_types.filter(
            (type) => type !== 'sepa_debit'
          )
        }
      })
    );
  });

  afterEach(() => {
    sinon.restore();
  });

  /** @type {Array<'ideal' | 'bancontact'>} */ (['ideal', 'bancontact']).forEach((type) => {
    it(`renews via a SEPA mandate generated by a first ${type} payment, without offering sepa_debit`, async () => {
      let { user, customer, usersPrivateRef, testClock } = await createAndLinkTestClockCustomer();

      const { subscriptionId, clientSecret } = await createOrRetrieveUnpaidSubscription(
        /** @type {FV2.CallableRequest<{priceId: string, locale: string}>} */ (
          /** @type {unknown} */ ({
            auth: { uid: user.uid },
            data: { priceId: process.env.STRIPE_PRICE_IDS_REDUCED, locale: 'en' }
          })
        )
      );
      const paymentIntentId = /** @type {string} */ (clientSecret).split('_secret_')[0];

      const paymentIntent = await stripe.paymentIntents.retrieve(paymentIntentId);
      assert.ok(!paymentIntent.payment_method_types.includes('sepa_debit'));
      assert.ok(paymentIntent.payment_method_types.includes(type));
      assert.equal(paymentIntent.setup_future_usage, 'off_session');

      // Pay like the Payment Element would, server-side
      await authorizeTestRedirect(
        await stripe.paymentIntents.confirm(paymentIntentId, {
          payment_method_data: {
            type,
            billing_details: { name: `${customer.name} Test`, email: customer.email }
          },
          mandate_data: {
            customer_acceptance: {
              type: 'online',
              online: { ip_address: '127.0.0.1', user_agent: 'mocha' }
            }
          },
          return_url: 'https://example.com/return'
        })
      );

      // The first charge generated a reusable SEPA Debit payment method and mandate
      const charge = await pollUntil(async () => {
        const { latest_charge, status } = await stripe.paymentIntents.retrieve(paymentIntentId, {
          expand: ['latest_charge']
        });
        return status === 'succeeded' && /** @type {Stripe.Charge} */ (latest_charge);
      });
      const { generated_sepa_debit, generated_sepa_debit_mandate } =
        charge.payment_method_details[type];
      const mandate = await stripe.mandates.retrieve(
        /** @type {string} */ (generated_sepa_debit_mandate)
      );
      assert.equal(mandate.type, 'multi_use');
      assert.equal(mandate.status, 'active');

      // --> invoice.paid switches the subscription to charge_automatically with that payment method
      await pollUntil(
        async () =>
          (await usersPrivateRef.get()).data().stripeSubscription.collectionMethod ===
          'charge_automatically'
      );
      const subscription = await stripe.subscriptions.retrieve(subscriptionId);
      assert.equal(subscription.collection_method, 'charge_automatically');
      assert.equal(subscription.default_payment_method, generated_sepa_debit);

      console.log('Advancing to 1 day after the renewal period');
      testClock = await stripe.testHelpers.testClocks.advance(testClock.id, {
        frozen_time: DateTime.fromSeconds(subscription.items.data[0].current_period_end)
          .plus({ days: 1 })
          .toSeconds()
      });
      testClock = await pollForTestClockReady(testClock);

      // The renewal is charged with the generated SEPA Debit payment method
      const renewalInvoice = await pollUntil(
        async () =>
          (await stripe.invoices.list({ subscription: subscriptionId })).data.find(
            (invoice) =>
              invoice.billing_reason === 'subscription_cycle' && invoice.status === 'paid'
          ),
        testClock
      );
      const renewalPaymentIntent = await getInvoicePaymentIntent(renewalInvoice.id);
      assert.equal(renewalPaymentIntent?.payment_method, generated_sepa_debit);
    }).timeout(0);
  });
});
